import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import dotenv from 'dotenv';
import pg from 'pg';
import { deleteQuestion } from '../lib/delete-question.cjs';

test('configured submissions and questionnaires agree with activation settings', { skip: process.env.TEST_DATABASE !== '1' }, async t => {
  dotenv.config({ quiet: true });
  const pool = new pg.Pool({ host: process.env.PGHOST, port: Number(process.env.PGPORT || 5432), database: process.env.PGDATABASE,
    user: process.env.PGUSER, password: process.env.PGPASSWORD, ssl: process.env.PGSSLMODE === 'require' ? { rejectUnauthorized: false } : undefined });
  const client = await pool.connect();
  t.after(async () => { await client.query('rollback'); client.release(); await pool.end(); });
  const schema = 'questionnaire_test_' + crypto.randomBytes(6).toString('hex');
  await client.query('begin');
  await client.query(`create schema ${schema}`);
  const modes = {
    ladder: ['inspection_points', 'question_options', 'inspections', 'inspection_results', 'submit_inspection'],
    fire: ['fire_inspection_points', 'fire_question_options', 'fire_inspections', 'fire_inspection_results', 'submit_fire_inspection'],
    firstaid: ['firstaid_inspection_points', 'firstaid_question_options', 'firstaid_inspections', 'firstaid_inspection_results', 'submit_firstaid_inspection']
  };
  for (const tables of Object.values(modes)) {
    for (const name of tables.slice(0, 4)) {
      await client.query(`create table ${schema}.${name} (like public.${name} including all)`);
      if (!name.endsWith('inspections')) {
        await client.query(`alter table ${schema}.${name} alter column id drop identity if exists`);
        await client.query(`alter table ${schema}.${name} alter column id drop default`);
        await client.query(`alter table ${schema}.${name} alter column id add generated by default as identity`);
      }
    }
  }
  const migration = readFileSync(new URL('../supabase/migrations/20261104000000_configured_questionnaires.sql', import.meta.url), 'utf8')
    .replaceAll('public.', schema + '.').replaceAll('search_path = public', 'search_path = ' + schema);
  await client.query(migration);
  const deletionMigration = readFileSync(new URL('../supabase/migrations/20261104010000_question_deletion.sql', import.meta.url), 'utf8')
    .replaceAll('public.', schema + '.').replaceAll('search_path = public', 'search_path = ' + schema);
  await client.query(deletionMigration);
  const typesMigration = readFileSync(new URL('../supabase/migrations/20261104020000_question_answer_types.sql', import.meta.url), 'utf8')
    .replaceAll('public.', schema + '.').replaceAll('search_path = public', 'search_path = ' + schema);
  await client.query(typesMigration);
  await client.query(`set local search_path to ${schema}`);
  const deletionPool = { connect: async () => ({ release() {}, query(sql, values) {
    if (sql.toLowerCase() === 'begin') return client.query('savepoint deletion_request');
    if (sql.toLowerCase() === 'commit') return client.query('release savepoint deletion_request');
    if (sql.toLowerCase() === 'rollback') return client.query('rollback to savepoint deletion_request');
    return client.query(sql, values);
  } }) };
  for (const [mode, tables] of Object.entries(modes)) {
    await t.test(mode, async () => {
      const points = `${schema}.${tables[0]}`;
      await client.query(`insert into ${points} (id, category, field_key, question, display_order, is_active, is_required, question_type) values
        (1,'section_1','inspector_name','Inspector Name',1,false,true,'text'),
        (2,'section_1','epf_number','EPF Number',2,true,false,'text'),
        (3,'section_1','inspection_date','Date',3,true,true,'date'),
        (4,'section_2','quantity','Quantity',4,false,true,'number'),
        (10,$1,'','Required checklist',10,true,true,'decision'),
        (11,$1,'','Inactive checklist',11,false,true,'decision'),
        (12,$1,'','Optional checklist',12,true,false,'decision')`, [mode === 'ladder' ? 'general' : mode]);
      for (const id of [10, 11, 12]) await client.query(`insert into ${schema}.${tables[1]} (question_id,option_label,option_value,sort_order,is_fail_value,is_active) values ($1,'Good','PASS',1,false,true),($1,'Bad','FAIL',2,true,true)`, [id]);
      const config = (await client.query(`select ${schema}.get_inspection_questionnaire($1::jsonb) as data`, [JSON.stringify({ mode })])).rows[0].data;
      assert.equal(config.fields.find(field => field.id === 1).is_active, false);
      assert.deepEqual(config.questions.map(question => question.id), [10, 12]);
      const payload = { submission_key: crypto.randomUUID(), inspector_name: 'Value from old form', epf_number: null, inspection_date: '2026-11-04',
        ladder_no: 'L-1', section: 'Test', height_feet: 10, ladder_type: 'extension', point_no: 'FE-1', location: 'Test', quantity: 'Stale quantity', extinguisher_type: 'CO2', box_no: 'FA-1',
        results: [{ point_id: 10, result: 'PASS' }, { point_id: 11, result: 'FAIL' }] };
      const submit = async data => (await client.query(`select ${schema}.${tables[4]}($1::jsonb) as data`, [JSON.stringify(data)])).rows[0].data;
      const first = await submit(payload);
      assert.equal(first.overall_result, 'PASS', 'inactive failures are ignored');
      const saved = (await client.query(`select * from ${schema}.${tables[2]} where id=$1`, [first.id])).rows[0];
      assert.equal(saved.inspector_name, null);
      if (mode === 'fire') assert.equal(saved.quantity, null);
      assert.equal((await client.query(`select count(*)::int as count from ${schema}.${tables[3]} where inspection_id=$1`, [first.id])).rows[0].count, 1);
      assert.deepEqual(await submit(payload), first, 'repeated submission is idempotent');
      const failed = await submit({ ...payload, submission_key: crypto.randomUUID(), results: [{ point_id: 10, result: 'PASS' }, { point_id: 12, result: 'FAIL', remarks: 'Optional item is faulty' }] });
      assert.equal(failed.overall_result, 'FAIL', 'optional defects still fail the inspection');
      await client.query(`update ${points} set is_active=true where id=1`);
      await client.query('savepoint expected_error');
      await assert.rejects(submit({ ...payload, submission_key: crypto.randomUUID(), inspector_name: null }), /Inspector Name is required/);
      await client.query('rollback to savepoint expected_error');
      await client.query(`update ${points} set is_required=false where id=1`);
      await submit({ ...payload, submission_key: crypto.randomUUID(), inspector_name: null });
      await client.query(`update ${points} set is_active=false where id=10`);
      await submit({ ...payload, submission_key: crypto.randomUUID(), inspector_name: null, results: [] });
      await deleteQuestion(deletionPool, { points: tables[0], options: tables[1], inspections: tables[2], results: tables[3] }, 3);
      assert.ok((await client.query(`select inspection_date from ${schema}.${tables[2]}`)).rows.every(row => row.inspection_date === null));
      const afterDeletion = await submit({ ...payload, submission_key: crypto.randomUUID(), inspector_name: null, results: [] });
      assert.equal((await client.query(`select inspection_date from ${schema}.${tables[2]} where id=$1`, [afterDeletion.id])).rows[0].inspection_date, null, 'deleted information data cannot reappear through submission defaults');
      const types = ['text', 'long_text', 'number', 'date', 'decision', 'yes_no', 'multiple_choice'];
      for (const [index, type] of types.entries()) {
        const questionId = 20 + index;
        await client.query(`insert into ${points} (id,category,question,question_type,display_order,is_required,is_active) values ($1,$2,$3,$4,$1,true,true)`, [questionId, mode === 'ladder' ? 'general' : mode, 'Typed ' + type, type]);
        if (index >= 4) await client.query(`insert into ${schema}.${tables[1]} (question_id,option_label,option_value,sort_order,is_fail_value,is_active) values ($1,'Good',$2,1,false,true),($1,'Bad','FAIL',2,true,true)`, [questionId, index === 5 ? 'YES' : index === 6 ? 'SAFE' : 'PASS']);
      }
      const results = ['FAIL', 'Line one\nLine two', 0, '2026-11-04', 'PASS', 'YES', 'SAFE'].map((value, index) => ({ point_id: 20 + index, value }));
      const typedPayload = { ...payload, submission_key: crypto.randomUUID(), inspector_name: null, results };
      const typed = await submit(typedPayload);
      assert.equal(typed.overall_result, 'PASS', 'free text FAIL must not affect the safety result');
      const typedRows = (await client.query(`select * from ${schema}.${tables[3]} where inspection_id=$1 order by inspection_point_id`, [typed.id])).rows;
      assert.equal(typedRows.length, 7);
      assert.deepEqual(typedRows.map(row => row.question_type_snapshot), types);
      assert.equal(typedRows[0].answer_value, 'FAIL');
      assert.equal(typedRows[0].answer_label, 'FAIL');
      assert.equal(typedRows[0].result, 'ANSWERED');
      assert.equal(typedRows[1].answer_value, 'Line one\nLine two');
      assert.equal(typedRows[2].answer_value, 0);
      assert.equal(typedRows[3].answer_value, '2026-11-04');
      for (const [index, invalid] of [[0, ' \n\t'], [0, []], [2, 'NaN'], [2, null], [3, '2026-02-30'], [5, 'unknown']]) {
        await client.query('savepoint invalid_typed_answer');
        await assert.rejects(submit({ ...typedPayload, submission_key: crypto.randomUUID(), results: results.map((answer, i) => i === index ? { ...answer, value: invalid } : answer) }));
        await client.query('rollback to savepoint invalid_typed_answer');
      }
      const withDefect = await submit({ ...typedPayload, submission_key: crypto.randomUUID(), results: results.map(answer => answer.point_id === 26 ? { ...answer, value: 'FAIL', remarks: 'Defect found' } : answer) });
      assert.equal(withDefect.overall_result, 'FAIL');
      await client.query(`update ${points} set is_required=false where id=20`);
      const optional = await submit({ ...typedPayload, submission_key: crypto.randomUUID(), results: results.filter(answer => answer.point_id !== 20) });
      assert.equal((await client.query(`select count(*)::int as count from ${schema}.${tables[3]} where inspection_id=$1`, [optional.id])).rows[0].count, 6);
    });
  }
});
